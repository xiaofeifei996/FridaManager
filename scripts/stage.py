#!/usr/bin/env python3
"""Normalize the unprefixed Theos after-stage tree; never install or build.

    python3 scripts/stage.py '$(THEOS_STAGING_DIR)' '$(THEOS_PACKAGE_SCHEME)'

RootHide bootstrap tools use jbroot-relative paths, not native paths. The
/rootfs escape below is intentional when a native jbroot() result is passed
back to a bootstrap filesystem tool. launchctl always receives a logical path.
Sources checked 2026-10-21:
  https://github.com/roothide/Developer/blob/main/interface.md
  https://github.com/roothide/Developer/blob/main/roothide.md
  https://github.com/roothide/libroothide/blob/7764c54759009272b4f2f23c18c62b21794fe6dd/cmdtool.c
  https://github.com/roothide/launchctl/blob/a869bc4e7cca20aaa26545104f1fd57fb9faff0e/plistpatch.m
  https://github.com/roothide/libSandy/blob/00089fd9bc3cc4c1ba9e85ec3cc8ab25791d1c2b/sandyd/main.m
"""

import argparse
import os
from pathlib import Path
import plistlib
import shutil
import sys
import tempfile

LABEL = "com.b1tbreaker.fridamanager"
DAEMON = "usr/local/bin/fridamgr"
BUNDLE = "Library/PreferenceBundles/FridaManagerPrefs.bundle"
PREFS_BINARY = BUNDLE + "/FridaManagerPrefs"
LAUNCH_PLIST = "Library/LaunchDaemons/" + LABEL + ".plist"
SANDY_PLIST = "Library/libSandy/" + LABEL + ".socket.plist"
SOCKET = "/var/run/fridamgr.sock"


def maintenance_script(scheme, role):
    """Return a deterministic, standalone POSIX dpkg maintainer script."""
    if scheme not in ("rootful", "rootless", "roothide"):
        raise ValueError("unsupported scheme: " + scheme)
    if role not in ("postinst", "prerm"):
        raise ValueError("unsupported maintainer script: " + role)
    prefix = "/var/jb" if scheme == "rootless" else ""
    path = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
    if scheme == "rootless":
        path = ":".join("/var/jb" + item for item in path.split(":")) + ":" + path
    actions = ("configure|abort-upgrade|abort-remove|abort-deconfigure"
               if role == "postinst" else "remove|upgrade|deconfigure|failed-upgrade")
    text = f'''#!/bin/sh
# Generated by scripts/stage.py; scheme={scheme}; role={role}
set -eu
PATH='{path}'
LC_ALL=C
export PATH LC_ALL
umask 022
case "${{1:-}}" in
    {actions}) ;;
    *) exit 0 ;;
esac
LABEL='{LABEL}'
DAEMON_PLIST='{prefix}/{LAUNCH_PLIST}'
DAEMON_BIN='{prefix}/{DAEMON}'
SANDY_PLIST='{prefix}/{SANDY_PLIST}'
SOCKET_PATH='{SOCKET}'
fail() {{ printf '%s\\n' "FridaManager: $*" >&2; exit 1; }}
'''
    if scheme == "roothide":
        text += '''# jbroot prints a native rootfs path; do not prepend a fixed UUID.
native_path() {
    /usr/bin/jbroot "$1"
}
fs_path() {
    resolved=$(native_path "$1") || return 1
    case "$resolved" in
        /*) printf '/rootfs%s\\n' "$resolved" ;;
        *) fail 'jbroot did not return an absolute path' ;;
    esac
}
'''
    else:
        text += '''native_path() { printf '%s\\n' "$1"; }
fs_path() { printf '%s\\n' "$1"; }
'''
    text += '''# Only the socket is transient. Preferences, history, logs and downloads stay.
SOCKET_FILE=$(fs_path "$SOCKET_PATH") || fail 'cannot resolve socket path'
stop_daemon() {
    if ! launchctl bootout "system/$LABEL" 2>/dev/null; then
        launchctl unload "$DAEMON_PLIST" 2>/dev/null || true
    fi
    killall fridamgr 2>/dev/null || true
}
'''
    if role == "postinst":
        text += '''# sun_path is 104 bytes on Darwin, including the terminating NUL.
# LC_ALL=C makes the shell length a byte count, not a character count.
SOCKET_NATIVE=$(native_path "$SOCKET_PATH") || fail 'cannot resolve native socket path'
if [ "${#SOCKET_NATIVE}" -ge 104 ]; then
    fail "socket path is ${#SOCKET_NATIVE} bytes; maximum is 103; shorten the shared FMPaths socket path"
fi
ensure_dir() {
    directory=$(fs_path "$1") || fail 'cannot resolve data directory'
    if [ ! -d "$directory" ]; then
        mkdir -p "$directory"
        chmod "$2" "$directory"
        chown "$3" "$directory"
    fi
}
ensure_dir /var/run 0755 root:wheel
ensure_dir /var/tmp 1777 root:wheel
ensure_dir /var/mobile 0755 mobile:mobile
ensure_dir /var/mobile/Library 0755 mobile:mobile
ensure_dir /var/mobile/Library/Preferences 0755 mobile:mobile
DAEMON_FILE=$(fs_path "$DAEMON_BIN") || fail 'cannot resolve daemon'
PLIST_FILE=$(fs_path "$DAEMON_PLIST") || fail 'cannot resolve launch plist'
SANDY_FILE=$(fs_path "$SANDY_PLIST") || fail 'cannot resolve sandbox profile'
chown root:wheel "$DAEMON_FILE" "$PLIST_FILE" "$SANDY_FILE"
chmod 0755 "$DAEMON_FILE"
chmod 0644 "$PLIST_FILE" "$SANDY_FILE"
# RootHide sandyd resolves profile path with jbroot() on every request.
# Keep its profile logical; storing a native path would double-prefix it and
# become stale after a jailbreak root rotation. No sandyd restart is needed.
stop_daemon
rm -f -- "$SOCKET_FILE"
launchctl enable "system/$LABEL" 2>/dev/null || true
if ! launchctl bootstrap system "$DAEMON_PLIST"; then
    launchctl load "$DAEMON_PLIST" || fail 'could not load launch daemon'
fi
'''
    else:
        text += '''# dpkg calls prerm upgrade before replacing files, not just prerm remove.
stop_daemon
rm -f -- "$SOCKET_FILE"
'''
    return text + "exit 0\n"


def sandbox_profile():
    # AllowedProcesses contains signing identifiers, not executable basenames.
    # This is the real opa334/RootHide libSandy schema (lowercase extension keys).
    return {
        "AllowedProcesses": ["com.apple.Preferences"],
        "Extensions": [{
            "type": "file",
            "extension_class": "com.apple.app-sandbox.read-write",
            "path": SOCKET,
        }],
    }


def atomic_write(path, data, mode):
    if path.is_symlink():
        raise ValueError("refusing to overwrite a staged symlink: " + str(path))
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def stage(directory, scheme):
    root = Path(directory).resolve(strict=True)
    project = Path(__file__).resolve().parent.parent
    if not root.is_dir() or root == Path("/") or root == project:
        raise ValueError("provide a staging directory, not / or the project root")
    scheme = scheme.strip() or "rootful"
    if scheme not in ("rootful", "rootless", "roothide"):
        raise ValueError("scheme must be empty, rootful, rootless or roothide")

    def local(relative):
        target = root / relative
        if target.is_symlink() or not target.resolve().is_relative_to(root):
            raise ValueError("staged path escapes the staging tree: " + relative)
        return target

    launch = local(LAUNCH_PLIST)
    binaries = [local(DAEMON), local(PREFS_BINARY)]
    for path in [launch] + binaries:
        if not path.is_file():
            raise ValueError("missing after-stage file (tree must be unprefixed): " + str(path))
    with launch.open("rb") as stream:
        daemon = plistlib.load(stream)
    if not isinstance(daemon, dict) or daemon.get("Label") != LABEL:
        raise ValueError("unexpected launch daemon Label or plist structure")
    daemon.pop("Program", None)
    daemon.pop("__Patched", None)
    daemon["ProgramArguments"] = [("/var/jb" if scheme == "rootless" else "") + "/" + DAEMON]

    control = local("DEBIAN")
    if not control.exists():
        # Theos normally copies layout/DEBIAN at before-package, but only if
        # DEBIAN does not exist. Preserve unrelated metadata before creating it.
        source = project / "layout/DEBIAN"
        if source.is_dir():
            shutil.copytree(source, control, ignore=shutil.ignore_patterns("postinst", "prerm", "extrainst_"))
        else:
            control.mkdir()
    if not control.is_dir():
        raise ValueError("staged DEBIAN is not a directory")
    control.chmod(0o755)
    extra = control / "extrainst_"
    if extra.exists() or extra.is_symlink():
        extra.unlink()
    for role in ("postinst", "prerm"):
        atomic_write(local("DEBIAN/" + role), maintenance_script(scheme, role).encode(), 0o755)
    sandy = local(SANDY_PLIST)
    sandy.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(sandy, plistlib.dumps(sandbox_profile(), sort_keys=False), 0o644)
    atomic_write(launch, plistlib.dumps(daemon, sort_keys=False), 0o644)
    for binary in binaries:
        binary.chmod(0o755)
    print(f"stage: {scheme}; launch + sandbox profile normalized; postinst/prerm=0755; extrainst_ removed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("staging_dir")
    parser.add_argument("scheme", help="empty/rootful, rootless, or roothide")
    args = parser.parse_args()
    try:
        stage(args.staging_dir, args.scheme)
    except (OSError, ValueError, plistlib.InvalidFileException) as error:
        parser.exit(1, f"stage: ERROR: {error}\n")


if __name__ == "__main__":
    main()
